import {test} from 'node:test'
import assert from 'node:assert/strict'
import {mkdtemp,mkdir,writeFile,rm,rename,symlink,readFile} from 'node:fs/promises'
import {tmpdir} from 'node:os'
import {join} from 'node:path'
import {execFile} from 'node:child_process'
import {promisify} from 'node:util'
const run=promisify(execFile)
import {workspaceDiff,workspaceDiffText} from './workspace-diff.mjs'

test('workspace changes are read-only, scoped to the session directory and separated by Git state',async t=>{
  const root=await mkdtemp(join(tmpdir(),'dsh-worktree-'))
  t.after(()=>rm(root,{recursive:true,force:true}))
  await assert.rejects(workspaceDiff(root),error=>error.status===422)
  await assert.rejects(workspaceDiff(undefined),error=>error.status===422)
  await assert.rejects(workspaceDiff(root,undefined,'history'),error=>error.status===400)
  await run('git',['init','-q'],{cwd:root})
  const folder=join(root,'folder')
  await mkdir(folder)
  await writeFile(join(root,'outside'),'outside')
  await writeFile(join(folder,'change'),'staged\n')
  await run('git',['add','--','folder/change','outside'],{cwd:root})
  const index=await readFile(join(root,'.git','index'))
  await writeFile(join(folder,'change'),'working\n')
  await writeFile(join(folder,'new'),'test\n')
  const staged=await workspaceDiff(folder,undefined,'staged')
  assert.deepEqual(staged.files.map(file=>[file.path,file.status,file.untracked]),[['change','added',false]])
  assert.deepEqual(staged.files[0].hunks,[{oldStart:1,oldLines:0,newStart:1,newLines:1,lines:['+staged']}])
  const unstaged=await workspaceDiff(folder,undefined,'unstaged')
  assert.deepEqual(unstaged.files.map(file=>file.path),['change','new'])
  assert.deepEqual(unstaged.files[0].hunks[0].lines,['-staged','+working'])
  assert.deepEqual(unstaged.files[1].hunks[0].lines,['+test'])
  assert.equal(unstaged.files[1].untracked,true)
  const all=await workspaceDiff(folder)
  assert.deepEqual(all.files.map(file=>file.path),['change','new'])
  assert.deepEqual(all.files[0].hunks[0].lines,['+working'])
  assert.equal(all.omitted,0)
  assert.deepEqual(await readFile(join(root,'.git','index')),index)
})

test('Git diff preserves quoted names, native layers, missing newlines and binary markers',async t=>{
  const root=await mkdtemp(join(tmpdir(),'dsh-forge-diff-'))
  t.after(()=>rm(root,{recursive:true,force:true}))
  const git=(...args)=>run('git',args,{cwd:root})
  await git('init','-q')
  const renamedContent='unchanged lines\n'.repeat(12)
  await writeFile(join(root,'before.txt'),renamedContent)
  await writeFile(join(root,'model.bin'),Buffer.from([0,1,2]))
  await writeFile(join(root,'interface.file'),'old\n')
  await writeFile(join(root,'.gitattributes'),'interface.file dsh-review-layer=interface\n')
  await git('add','.')
  await git('-c','user.name=Fixture','-c','user.email=fixture@example.invalid','commit','-qm','fixture')
  const after='新 名\tquote".txt'
  await rename(join(root,'before.txt'),join(root,after))
  await writeFile(join(root,after),renamedContent+'one new line\n')
  await git('add','--all')
  await writeFile(join(root,'model.bin'),Buffer.from([0,1,3]))
  await writeFile(join(root,'interface.file'),'new\n')
  await writeFile(join(root,'unit.test.js'),'line without newline')
  const results=await workspaceDiff(root)
  const files=new Map(results.files.map(file=>[file.path,file]))
  assert.deepEqual([files.get(after).previousPath,files.get(after).status],['before.txt','renamed'])
  assert.ok(files.get(after).hunks[0].lines.includes('+one new line'))
  assert.deepEqual([files.get('model.bin').binary,files.get('model.bin').hunks],[true,[]])
  assert.equal(files.get('interface.file').layer,'interface')
  assert.equal(files.get('unit.test.js').layer,'test')
  assert.deepEqual(files.get('unit.test.js').hunks[0].lines,['+line without newline','\\ No newline at end of file'])
  assert.equal((await workspaceDiff(root)).files.find(file=>file.path==='model.bin').digest,files.get('model.bin').digest)
})

test('diff disables configured executable filters and reads a symlink as a link',async t=>{
  const root=await mkdtemp(join(tmpdir(),'dsh-diff-filter-'))
  t.after(()=>rm(root,{recursive:true,force:true}))
  const repo=join(root,'repo')
  await mkdir(repo)
  const git=(...args)=>run('git',args,{cwd:repo})
  await git('init','-q')
  await writeFile(join(repo,'.gitattributes'),'*.text filter=record\n')
  await writeFile(join(repo,'demo.text'),'original\n')
  await git('add','.')
  await git('-c','user.name=Fixture','-c','user.email=fixture@example.invalid','commit','-qm','fixture')
  const ran=join(root,'filter-ran')
  await git('config','filter.record.clean',`touch ${ran}; cat`)
  await git('config','filter.record.required','true')
  await writeFile(join(repo,'demo.text'),'new contents\n')
  await writeFile(join(root,'outside'), 'this file is outside the workspace')
  await symlink('../outside', join(repo,'external-link'))
  const {files}=await workspaceDiff(repo)
  assert.deepEqual(files.find(file=>file.path==='demo.text').hunks[0].lines,['-original','+new contents'])
  assert.deepEqual(files.find(file=>file.path==='external-link').hunks[0].lines,['+../outside','\\ No newline at end of file'])
  await assert.rejects(readFile(ran),error=>error.code==='ENOENT')
})

test('diff reports oversized files without their contents and counts unlisted untracked paths',async t=>{
  const root=await mkdtemp(join(tmpdir(),'dsh-diff-limits-'))
  t.after(()=>rm(root,{recursive:true,force:true}))
  await run('git',['init','-q'],{cwd:root})
  await writeFile(join(root,'000-large'),Buffer.alloc(2*1024*1024+1,65))
  for(let i=1;i<=101;i++) await writeFile(join(root,String(i).padStart(3,'0')), '')
  const {files,omitted}=await workspaceDiff(root)
  assert.equal(files.length,100)
  assert.equal(omitted,2)
  assert.equal(files[0].path,'000-large')
  assert.equal(files[0].oversized,true)
  assert.deepEqual(files[0].hunks,[])
})

test('unchanged context reads the chosen Git side and requires the displayed file digest',async t=>{
  const root=await mkdtemp(join(tmpdir(),'dsh-forge-context-'))
  t.after(()=>rm(root,{recursive:true,force:true}))
  const git=(...args)=>run('git',args,{cwd:root})
  await git('init','-q')
  const folder=join(root,'folder')
  await mkdir(folder)
  const name='file [a].txt'
  const path=join(folder,name)
  const base='first\n'+Array.from({length:24},(_,i)=>`context ${i}\n`).join('')
  const staged=base.replace('context 15','index change')
  const worktree=staged.replace('context 20','working change')
  await writeFile(path,base)
  await git('add','--',`folder/${name}`)
  await git('-c','user.name=Fixture','-c','user.email=fixture@example.invalid','commit','-qm','fixture')
  await writeFile(path,staged)
  await git('add','--',`folder/${name}`)
  await writeFile(path,worktree)
  const indexed=(await workspaceDiff(folder,undefined,'staged')).files[0]
  const working=(await workspaceDiff(folder,undefined,'unstaged')).files[0]
  assert.deepEqual(await workspaceDiffText(folder,undefined,'staged',name,indexed.digest),{text:staged})
  assert.deepEqual(await workspaceDiffText(folder,undefined,'unstaged',name,working.digest),{text:worktree})
  await assert.rejects(workspaceDiffText(folder,undefined,'staged',name,working.digest),{status:409})
  await assert.rejects(workspaceDiffText(folder,undefined,'staged',`../${name}`,indexed.digest),{status:400})
  await writeFile(path,worktree.replace('working change','changed again'))
  await assert.rejects(workspaceDiffText(folder,undefined,'unstaged',name,working.digest),{status:409})
})
